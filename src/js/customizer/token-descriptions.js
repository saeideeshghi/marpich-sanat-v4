export const TOKEN_DEVICE_NAMES = { desktop: "دسکتاپ", tablet: "تبلت", mobile: "موبایل", compact: "موبایل کوچک" };

export function describeToken(name) {
    const key = name.replace(/^--/, "");
    const match = key.match(/-(desktop|tablet|mobile|compact)$/);
    const device = match?.[1] || "";
    const family = device ? key.slice(0, -(device.length + 1)) : key;
    let definition = definitions[family];
    if (!definition && family === "hero-summary-overlap") definition = definitions["hero-summary-overlap-preferred"];
    if (device && family === "hero-summary-overlap") definition = definitions["hero-summary-overlap-preferred"];
    if (!definition) {
        for (const [prefix, [page, group]] of Object.entries(pageColors)) {
            if (!family.startsWith(`${prefix}-`)) continue;
            const part = colorParts[family.slice(prefix.length + 1)];
            if (part)
                definition = [`${part[0]} ${page}`, group, `${part[1]} در صفحهٔ ${page}؛ مستقل از رنگ عمومی برند است.`];
        }
    }
    if (!definition) throw new Error(`Missing design-token explanation: ${name}`);
    const [label, group, description] = definition;
    return {
        label: `${label}${device ? ` · ${TOKEN_DEVICE_NAMES[device]}` : ""}`,
        group,
        description: `${description}${device ? ` این ورودی مخصوص ${TOKEN_DEVICE_NAMES[device]} است؛ نام بدون پسوند، مقدار فعال را نشان می‌دهد.` : ""}`,
        family: `--${family}`,
        device,
    };
}
